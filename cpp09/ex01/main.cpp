#include "RPN.hpp"

int	main(int argc, char **argv)
{

	if (argc != 2)
	{
		std::cerr	<< "Error\n";
		return (1);
	}

	try
	{
		RPN	rpn;
		rpn.evaluate(argv[1]);
	}
	catch(...)
	{
		std::cerr << "Error\n";
		return (1);
	}

	return (0);
}

